import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { groupLine, headlineTable, recordedLine, speedSearchLine, type EvalRow, type EvalSummary } from "./report";

// The results block in README.md is generated from the newest live result file.
// npm run readme writes it; tests/readme-numbers.test.ts fails if they differ.

export const START = "<!-- eval:start (generated by npm run readme from the newest eval/results/live-*.json; do not edit by hand) -->";
export const END = "<!-- eval:end -->";

export function latestLiveResult(dir = "eval/results"): { file: string; summary: EvalSummary; rows: EvalRow[] } {
  const files = readdirSync(dir)
    .filter((f) => /^live-.*\.json$/.test(f))
    .sort();
  const file = files.at(-1);
  if (!file) throw new Error("no live result file in eval/results");
  const j = JSON.parse(readFileSync(join(dir, file), "utf8")) as { summary: EvalSummary; rows: EvalRow[] };
  return { file, ...j };
}

export function readmeBlock(file: string, summary: EvalSummary, rows: EvalRow[]): string {
  return [
    START,
    `Latest live run: \`eval/results/${file.replace(/\.json$/, ".md")}\` (${summary.ranAt.slice(0, 10)}, ${summary.cases} cases). Agent models: ${summary.models.agent.join(", ")}. Baseline: ${summary.models.baseline ?? "not run"}.`,
    ``,
    headlineTable(summary, rows),
    ``,
    `- ${recordedLine(rows)}`,
    `- Fair Shift by group: ${groupLine(rows)}.`,
    `- ${speedSearchLine(rows)}`,
    END,
  ].join("\n");
}

export function replaceBlock(readme: string, block: string): string {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < 0) throw new Error("README has no eval block markers");
  return readme.slice(0, a) + block + readme.slice(b + END.length);
}
